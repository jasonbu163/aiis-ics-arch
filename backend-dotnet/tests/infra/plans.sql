CREATE TABLE plans (
  `id` INT NOT NULL AUTO_INCREMENT,
  `coil_no` VARCHAR(50) NOT NULL,
  `grade` VARCHAR(20) NOT NULL,
  `spec` VARCHAR(50) NOT NULL,
  `weight` DECIMAL(12,4) NOT NULL,
  `thickness` DECIMAL(10,3) NOT NULL,
  `width` DECIMAL(10,2) NOT NULL,
  `material_status` VARCHAR(20) NOT NULL,
  `density` DECIMAL(10,2) NOT NULL,
  `entry_length` DECIMAL(10,2) NOT NULL,
  `uncoiler1_tension` DECIMAL(10,2) NOT NULL,
  `exit_tension` DECIMAL(10,2) NOT NULL,
  `process1_tension` DECIMAL(10,2) NOT NULL,
  `entry_loop_tension` DECIMAL(10,2) NOT NULL,
  `exit_loop_tension` DECIMAL(10,2) NOT NULL,
  `entry_unit_tension` DECIMAL(12,4) NOT NULL,
  `entry_loop_unit_tension` DECIMAL(12,4) NOT NULL,
  `process_unit_tension` DECIMAL(12,4) NOT NULL,
  `exit_loop_unit_tension` DECIMAL(12,4) NOT NULL,
  `exit_unit_tension` DECIMAL(12,4) NOT NULL,
  `status` VARCHAR(20) NOT NULL,
  `priority` SMALLINT NOT NULL,
  `remark` VARCHAR(500) NULL,
  `created_at` DATETIME(0) NOT NULL,
  `updated_at` DATETIME(0) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY ix_plans_coil_no (coil_no),
  KEY ix_plans_id (id),
  KEY ix_plans_priority (priority),
  KEY ix_plans_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
